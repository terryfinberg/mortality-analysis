"""The submission artifacts, and the two ways they can quietly go wrong.

Both failures this file guards against were real. A figure was generated by
``src/figures.py``, committed, archived on Zenodo, and cited by nothing --
found by eye while wiring up the export, not by anything failing. And an
anonymised build is the kind of artifact whose defect is invisible in the
thing itself: a PDF with the author's name still in it looks exactly like one
without, until a reviewer opens it.

Nothing here requires pandoc. The document-shaping logic is pure Python and is
tested directly; the pandoc invocation is a thin wrapper over it.
"""
import json
import re
import shutil

import pytest

from src import export, report

ROOT = export.ROOT
FIG_DIR = ROOT / "figures"


@pytest.fixture(scope="module")
def identity():
    return export.Identity.load()


@pytest.fixture(scope="module")
def built():
    return export.SOURCE.read_text(encoding="utf-8")


