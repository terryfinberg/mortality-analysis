def test_internal_notes_do_not_reach_a_submission(identity):
    md = export.prepare(identity, anonymous=False)
    for marker in export.INTERNAL_MARKERS:
        assert marker not in md, f"internal note reached the submission: {marker!r}"


def test_identity_comes_from_the_citation_record(identity):
    """Retyping the author into the exporter is the drift this avoids."""
    md = export.prepare(identity, anonymous=False)
    assert identity.author == "Terry Finberg"
    assert identity.orcid.endswith("0009-0006-1598-4200")
    assert identity.author in md
    assert export.AFFILIATION in md
    assert identity.orcid in md
    assert identity.title.startswith("Decomposing U.S. Crude Death Rates")


def test_keywords_survive_and_respect_the_ten_limit(identity):
    """Demographic Research allows up to ten; CITATION.cff is the source."""
    assert 1 <= len(identity.keywords) <= 10
    md = export.prepare(identity, anonymous=False)
    for kw in identity.keywords:
        assert kw in md


def test_keywords_are_visible_prose_not_a_metadata_key(identity):
    """The keywords line is in the body, and the YAML key must stay gone.

    Two things depend on this. Pandoc 3.6.2's typst template renders a
    keywords list as `keywords: (,,,,,,,,,)` -- separators without values --
    and typst then refuses to compile, so the PDF silently stopped being a
    PDF and fell back to a browser. And Demographic Research wants the
    keywords *listed in the file*, which a document property nobody opens
    does not satisfy.
    """
    md = export.prepare(identity, anonymous=False)
    front = md.split("---", 2)[1]
    assert "keywords:" not in front, (
        "keywords are back in the YAML block; this breaks the typst PDF"
    )
    assert "**Keywords:** " + ", ".join(identity.keywords) in md


CONCEPT_DOI = "10.5281/zenodo.22263667"


def test_nothing_in_the_archive_names_its_own_version_doi(built, identity):
    """A deposit cannot contain the identifier of the deposit containing it.

    Zenodo mints a version DOI when it archives the release, which is after
    the commit the release is cut from. So a version DOI written into the
    manuscript or into CITATION.cff's `doi:` is either an identifier that
    does not exist yet or the *previous* release's, attached to a new version
    number -- which is what this file read before v0.1.1, and is the same
    class of error as a date-released describing a release that never
    happened.

    Version DOIs belong on the Zenodo record and under CITATION.cff's
    `identifiers:`, added after their release was archived.
    """
    assert identity.version_doi == CONCEPT_DOI, (
        f"CITATION.cff `doi:` is {identity.version_doi!r}; it must be the "
        f"concept DOI {CONCEPT_DOI!r}. Version DOIs go under identifiers:."
    )
    found = set(re.findall(r"10\.5281/zenodo\.\d+", built))
    assert found == {CONCEPT_DOI}, (
        f"the manuscript cites {sorted(found)}; it may cite only the concept "
        f"DOI. A version DOI in the manuscript cannot be true at tag time."
    )


def test_the_manuscript_names_the_release_from_the_citation_record(built):
    """`v{{RELEASE_VERSION}}` must agree with CITATION.cff, not be typed."""
    version = report._release_version()
    assert f"release `v{version}`" in built
    template = (ROOT / "paper" / "manuscript.md").read_text(encoding="utf-8")
    assert "{{RELEASE_VERSION}}" in template, (
        "the release string was typed into the template; it goes stale at the "
        "next tag"
    )


def test_the_browser_fallback_is_opt_in(monkeypatch, tmp_path):
    """A missing engine must fail, not quietly produce a browser PDF.

    It used to fall back silently-in-effect: the run printed one line naming
    the engine, and one line is easy to miss. The resulting PDF is
    indistinguishable from a good one without reading its metadata, which is
    a bad way to find out after a preprint is posted.
    """
    monkeypatch.setattr(export, "find_pdf_engine", lambda: None)
    with pytest.raises(export.ExportError, match="opt-in"):
        export.build_pdf("# x\n", tmp_path / "out.pdf", allow_browser=False)


def test_the_fallback_reports_itself_as_a_fallback():
    """Whatever the browser path returns must be recognisable as one.

    run() decides whether to print the warning by looking for "fallback" in
    the engine string, so that word carries load and a rename would silence
    the warning without failing anything.
    """
    src = (ROOT / "src" / "export.py").read_text(encoding="utf-8")
    assert 'headless (fallback)"' in src
    assert '"fallback" in engine' in src


def test_the_typst_path_names_a_font(identity):
    """typst 0.15 rejects an empty font fallback list, which is pandoc's default.

    Without an explicit font the document does not compile at all. The face
    named must be one typst bundles, or the build stops being reproducible
    across machines.
    """
    assert export.TYPST_FONT
    assert export.TYPST_FONT in ("Libertinus Serif", "New Computer Modern")


