def test_anonymous_build_carries_nothing_identifying(identity):
    md = export.prepare(identity, anonymous=True)
    # prepare() runs the assertion itself; run it again explicitly so this
    # test fails here rather than somewhere inside the builder.
    export._assert_anonymous(md)
    for pattern in export.IDENTIFYING:
        assert not re.search(pattern, md, re.I), f"leaked: {pattern}"


def test_anonymous_build_still_declares_availability(identity):
    """Stripped, not deleted.

    A reviewer must be able to see that the statement exists and was withheld.
    A submission with no data availability statement reads as an author who
    did not write one.
    """
    md = export.prepare(identity, anonymous=True)
    assert "**Data availability.**" in md
    assert "withheld from this anonymised copy" in md
    assert "**Author contributions.**" in md
    assert "**ORCID.**" not in md


def test_the_leak_check_actually_catches_a_leak():
    """A checker with a hole in it reports the absence of a search as a pass."""
    with pytest.raises(export.ExportError, match="identifying"):
        export._assert_anonymous("Written by Terry Finberg.")
    with pytest.raises(export.ExportError, match="identifying"):
        export._assert_anonymous("See https://github.com/someone/repo")


def test_anonymous_and_identified_differ_only_where_intended(identity):
    """The science must be byte-identical; only the front matter moves."""
    ident = export.prepare(identity, anonymous=False)
    anon = export.prepare(identity, anonymous=True)
    marker = "## 1. Introduction"
    assert ident[ident.index(marker):ident.index("## Declarations")] == \
        anon[anon.index(marker):anon.index("## Declarations")]


