def test_every_generated_figure_is_cited(built):
    """A figure nobody cites is a figure nobody meant to publish.

    fig2_age_specific_rates.png was generated, committed and archived while
    the manuscript referred to figures 1, 5, 3 and 4 and never to it. The
    export embeds what the manuscript cites, so an uncited figure silently
    does not ship -- and an archive that carries an image the paper never
    mentions invites the reader to wonder what it was for.
    """
    on_disk = {p.name for p in FIG_DIR.glob("*.png")}
    cited = set(re.findall(r"\((?:figures/)([\w.-]+\.png)\)", built))
    assert on_disk, "no figures found; run python -m src.report"
    assert on_disk == cited, (
        f"generated but never cited: {sorted(on_disk - cited)}; "
        f"cited but not generated: {sorted(cited - on_disk)}"
    )


def test_figures_use_image_syntax_not_filename_prose(built):
    """Captions must be markdown images, or the export ships filenames.

    The manuscript used to carry lines like "*Figure 1:
    `figures/fig1_crude_vs_adjusted.png`*", which is prose naming a file. It
    renders as literal text in Word and in a PDF, so a reviewer receives the
    path instead of the plot.
    """
    offenders = [
        ln for ln in built.splitlines()
        if "figures/" in ln and not ln.lstrip().startswith("![")
    ]
    assert not offenders, (
        "figure referenced as text rather than an embedded image:\n  "
        + "\n  ".join(offenders)
    )


def test_every_table_has_a_caption(built):
    """Both tables carry a `Table:` caption pandoc can turn into a real one."""
    tables = built.count("\n|---")
    captions = len(re.findall(r"^Table: ", built, re.M))
    assert tables == captions == 2, (
        f"{tables} tables but {captions} captions; a table without a caption "
        "arrives in Word as an unlabelled grid"
    )


