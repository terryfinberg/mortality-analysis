"""Build submission artifacts from the generated manuscript.

The same principle as ``report.py``, one level out. ``report.py`` exists so a
number cannot reach the paper without the code having produced it; this module
exists so a *submission* cannot reach a journal without the manuscript having
produced it. Nothing here is hand-assembled: the input is
``paper/manuscript_built.md``, which is itself generated, and the author
identity comes out of ``CITATION.cff`` rather than being retyped. A title page
that disagrees with the citation record is the same two-places-disagree failure
the repository already guards against elsewhere.

Two targets, two venues:

    python -m src.export --pdf     medRxiv
    python -m src.export --docx    Demographic Research, which prefers Word
    python -m src.export           both

Anonymised variants, for a venue that wants identifying information out of the
file itself:

    python -m src.export --anonymous

Outputs land in ``dist/``, which is gitignored. They are derived artifacts and
are rebuilt from source in one command, so committing them would be committing
a copy of something the repository can already produce.
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PAPER = ROOT / "paper"
ASSETS = PAPER / "assets"
DIST = ROOT / "dist"
SOURCE = PAPER / "manuscript_built.md"
CITATION = ROOT / "CITATION.cff"

AFFILIATION = "Independent researcher"

# Bundled with typst, so the PDF renders identically wherever the build runs.
TYPST_FONT = "Libertinus Serif"

# Lines the built manuscript carries for the benefit of whoever edits the
# repository, which have no business in a submitted document. Matched on a
# distinctive fragment rather than the whole line, so rewording the banner does
# not silently stop stripping it.
INTERNAL_MARKERS = (
    "Every number in this document is generated by the analysis code",
    "Built from `paper/manuscript.md` by `src/report.py`",
)


class ExportError(RuntimeError):
    """Something the user has to fix, reported without a traceback."""


# --------------------------------------------------------------------------
# Identity, read from the citation record rather than retyped
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class Identity:
    title: str
    author: str
    orcid: str
    keywords: list[str]
    version_doi: str

    @classmethod
    def load(cls) -> "Identity":
        cff = yaml.safe_load(CITATION.read_text(encoding="utf-8"))
        a = cff["authors"][0]
        return cls(
            title=" ".join(cff["title"].split()),
            author=f"{a['given-names']} {a['family-names']}",
            orcid=a.get("orcid", ""),
            keywords=list(cff.get("keywords", []))[:10],
            version_doi=cff.get("doi", ""),
        )


# --------------------------------------------------------------------------
# Source preparation
# --------------------------------------------------------------------------


def _strip_internal(text: str) -> str:
    """Drop the repository's own notes-to-self and the title block.

    The title and author line are removed here and reinstated as pandoc
    metadata, so the same document can be built with a full title page or
    with none at all.
    """
    lines = text.splitlines()
    kept = [
        ln for ln in lines
        if not any(m in ln for m in INTERNAL_MARKERS)
    ]
    out = "\n".join(kept)
    out = re.sub(r"^# .*?\n", "", out, count=1)
    out = re.sub(r"^\*\*Author:\*\*.*?\n", "", out, count=1, flags=re.M)
    # The first horizontal rule separated the stripped title block from the
    # abstract and now separates nothing.
    out = re.sub(r"\A[\s\-]*\n---\n", "", out)
    return out.lstrip("\n")


# Substitutions applied for --anonymous. Each replaces a specific identifying
# fact with a statement of what was removed, rather than deleting silently: a
# reviewer should be able to see that a data availability statement exists and
# was withheld, not conclude that the authors omitted one.
ANONYMOUS_RULES: list[tuple[str, str]] = [
    (
        r"\*\*ORCID\.\*\*[^\n]*\n\n",
        "",
    ),
    (
        r"\*\*Author contributions\.\*\*[^\n]*\n",
        "**Author contributions.** The sole author is responsible for all aspects "
        "of the work: conceptualisation, data curation, analysis, software, and "
        "writing. Author identity is withheld from this anonymised copy.\n",
    ),
    (
        r"\*\*Data availability\.\*\*[^\n]*\n",
        "**Data availability.** All code and data needed to reproduce every number "
        "and figure in this manuscript are archived in a public repository under a "
        "permanent DOI, and the analysis is fully reproducible from that archive. "
        "The DOI and repository URL identify the author and are withheld from this "
        "anonymised copy; they have been supplied to the editorial office.\n",
    ),
]

# Anything matching these must not survive into an anonymised build. Checked
# after the rules run, because a rule that stops matching -- the Declarations
# get reworded, say -- would otherwise fail open and ship the name.
IDENTIFYING = (
    r"Terry\s+Finberg",
    r"terryfinberg",
    r"orcid\.org/\d",
    r"0009-0006-1598-4200",
    r"10\.5281/zenodo",
    r"github\.com/\S+",
)


def _anonymise(text: str, identity: Identity) -> str:
    for pattern, replacement in ANONYMOUS_RULES:
        text = re.sub(pattern, replacement, text)
    text = text.replace(identity.author, "[author name withheld]")
    return text


def _assert_anonymous(text: str) -> None:
    hits = sorted({
        m.group(0)
        for pattern in IDENTIFYING
        for m in re.finditer(pattern, text, re.I)
    })
    if hits:
        raise ExportError(
            "anonymised build still contains identifying strings: "
            + ", ".join(repr(h) for h in hits)
            + "\nAdd a rule to ANONYMOUS_RULES in src/export.py."
        )


def prepare(identity: Identity, anonymous: bool) -> str:
    """The markdown that goes to pandoc, metadata block included."""
    body = _strip_internal(SOURCE.read_text(encoding="utf-8"))
    if anonymous:
        body = _anonymise(body, identity)
        _assert_anonymous(body)

    # Keywords go in the body, not the metadata block.
    #
    # Two reasons, one forced and one wanted. Pandoc 3.6.2's typst template
    # renders a keywords list as `keywords: (,,,,,,,,,)` -- it emits the
    # separators and not the values -- and typst then refuses the document.
    # That is a pandoc bug and it fires for every input form, inline list and
    # block sequence alike. Independently, Demographic Research asks for the
    # keywords to be *listed in the file*, which document properties nobody
    # opens do not satisfy. A visible line fixes both.
    #
    # The docx build still sets the document property, passed on the command
    # line where the writer handles it correctly. See build_docx().
    if identity.keywords:
        line = "**Keywords:** " + ", ".join(identity.keywords) + "\n"
        marker = "\n---\n\n## 1. Introduction"
        if marker in body:
            body = body.replace(marker, f"\n{line}{marker}", 1)
        else:
            raise ExportError(
                "could not place the keywords line: the abstract no longer "
                "ends with a rule before section 1. Fix the marker in "
                "src/export.py rather than dropping the keywords."
            )

    meta: dict = {
        "title": identity.title,
        "lang": "en-US",
    }
    if not anonymous:
        author: dict = {"name": identity.author, "affiliation": AFFILIATION}
        if identity.orcid:
            author["orcid"] = identity.orcid
        meta["author"] = [author]
        # Pandoc's default templates render a plain author list, so the
        # affiliation and ORCID are also emitted as a visible subtitle line.
        # Losing them to a template that ignores structured author fields is
        # the failure mode this avoids.
        byline = [identity.author, AFFILIATION]
        if identity.orcid:
            byline.append(f"ORCID: {identity.orcid}")
        meta["author"] = [" · ".join(byline)]
    else:
        meta["author"] = []

    front = yaml.safe_dump(meta, allow_unicode=True, sort_keys=False,
                           default_flow_style=False, width=100)
    return f"---\n{front}---\n\n{body}"


