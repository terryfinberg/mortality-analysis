# Pandoc
# --------------------------------------------------------------------------

# PDF engines in descending order of how well they suit a journal submission.
# The browser fallback is last and is genuinely a fallback: it is the only one
# whose output depends on a version of a program the repository cannot pin.
LATEX_ENGINES = ("tectonic", "xelatex", "lualatex", "pdflatex")
OTHER_ENGINES = ("typst", "weasyprint", "wkhtmltopdf")

BROWSERS = (
    Path("C:/Program Files/Google/Chrome/Application/chrome.exe"),
    Path("C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe"),
)

# Writers that number figures and tables themselves. The Lua filter must not
# run for these or every caption reads "Figure 1: Figure 1: ...".
SELF_NUMBERING = {"latex", "typst", "context"}


def _require_pandoc() -> str:
    exe = shutil.which("pandoc")
    if not exe:
        raise ExportError(
            "pandoc is not installed, and every output here goes through it.\n"
            "  winget install --id JohnMacFarlane.Pandoc\n"
            "or see https://pandoc.org/installing.html"
        )
    return exe


def find_pdf_engine() -> tuple[str, str] | None:
    """(engine name, writer) for the best available engine, or None."""
    for name in LATEX_ENGINES:
        if shutil.which(name):
            return name, "latex"
    for name in OTHER_ENGINES:
        if shutil.which(name):
            return name, "typst" if name == "typst" else "html"
    return None


def find_browser() -> Path | None:
    for path in BROWSERS:
        if path.exists():
            return path
    return None


def _pandoc(md: str, out: Path, writer: str, extra: list[str]) -> None:
    cmd = [
        _require_pandoc(),
        "--from", "markdown+pipe_tables+implicit_figures+yaml_metadata_block",
        "--standalone",
        "--resource-path", str(ROOT),
        "--output", str(out),
    ]
    if writer not in SELF_NUMBERING:
        cmd += ["--lua-filter", str(ASSETS / "number-captions.lua")]
    cmd += extra
    result = subprocess.run(cmd, input=md, text=True, encoding="utf-8",
                            capture_output=True, cwd=ROOT)
    if result.returncode != 0:
        raise ExportError(
            f"pandoc failed writing {out.name}:\n{result.stderr.strip()}"
        )
    if result.stderr.strip():
        for line in result.stderr.strip().splitlines():
            print(f"    pandoc: {line}", file=sys.stderr)


def build_docx(md: str, out: Path, keywords: list[str] | None = None) -> Path:
    extra = ["--to", "docx", "--toc-depth", "3"]
    if keywords:
        # Word's Keywords document property. Passed here rather than in the
        # YAML block because the same key breaks the typst writer; see
        # prepare().
        extra += ["--metadata", "keywords=" + ", ".join(keywords)]
    _pandoc(md, out, "docx", extra)
    return out


def build_pdf(md: str, out: Path, allow_browser: bool = False) -> tuple[Path, str]:
    """Returns (path, description of the engine used).

    The browser fallback is opt-in. It was not, and the reason it is now is
    worth keeping: a run that quietly degrades to headless Chrome prints one
    line saying so, and one line is easy to scroll past. A PDF built that way
    is indistinguishable from a good one until somebody reads its metadata,
    which is a poor place to discover it after a preprint is posted.

    Failing instead means the person who wanted a submission PDF is told to
    install an engine, and the person who genuinely wants a rough preview
    passes --allow-browser-fallback and knows what they are getting.
    """
    engine = find_pdf_engine()
    if engine:
        name, writer = engine
        extra = ["--pdf-engine", name]
        if writer == "latex":
            extra += [
                "--variable", "geometry:margin=1in",
                "--variable", "fontsize=11pt",
                "--variable", "linkcolor=blue",
            ]
        elif writer == "typst":
            # A font must be named. Pandoc's typst template defaults to
            # `font: ()` and typst 0.15 rejects an empty fallback list with
            # "font fallback list must not be empty", so the document fails to
            # compile at all rather than falling back to a default.
            #
            # Libertinus Serif ships with typst itself, so this renders the
            # same on any machine that can run the build -- which a
            # system-installed face like Georgia would not.
            extra += [
                "--variable", f"mainfont={TYPST_FONT}",
                "--variable", "fontsize=11pt",
            ]
        _pandoc(md, out, writer, extra)
        return out, name

    install_hint = (
        "  winget install --id Typst.Typst          (small, fast, recommended)\n"
        "  winget install --id MiKTeX.MiKTeX        (full LaTeX)\n"
        "then re-run. DOCX needs neither and builds already.\n"
        "\n"
        "If a rough preview is all you want, --allow-browser-fallback renders it\n"
        "through headless Chrome. Do not submit that output: it depends on a\n"
        "browser version this repository cannot pin."
    )
    if not allow_browser:
        raise ExportError(
            "No PDF engine found, and the browser fallback is opt-in.\n"
            f"{install_hint}"
        )

    browser = find_browser()
    if not browser:
        raise ExportError(
            "No PDF engine, and no browser to fall back on either. Install one:\n"
            f"{install_hint}"
        )

    html = out.with_suffix(".html")
    _pandoc(md, html, "html", [
        "--to", "html5",
        "--embed-resources",
        "--css", str(ASSETS / "export.css"),
        "--metadata", "document-css=false",
    ])
    subprocess.run(
        [str(browser), "--headless", "--disable-gpu", "--no-pdf-header-footer",
         "--run-all-compositor-stages-before-draw",
         f"--print-to-pdf={out}", html.resolve().as_uri()],
        check=True, capture_output=True, timeout=180,
    )
    if not out.exists():
        raise ExportError(f"{browser.name} produced no PDF at {out}")
    return out, f"{browser.stem} headless (fallback)"


